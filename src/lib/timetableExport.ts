import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import * as XLSX from "xlsx";

const DAYS = ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];

function formatTime(time: string): string {
  if (!time) return "";
  const [h, m] = time.split(":");
  const hour = parseInt(h);
  const ampm = hour >= 12 ? "PM" : "AM";
  const displayHour = hour > 12 ? hour - 12 : hour === 0 ? 12 : hour;
  return `${displayHour}:${m} ${ampm}`;
}

// ─── shared data builder ─────────────────────────────────────────────────────

export interface TimetableRow {
  periodLabel: string; // "1st Period (9:00–9:15 AM)"
  cells: string[];     // one per day [Mon…Sat]
  isBreak: boolean;
}

export function buildTimetableRows(
  periods: any[],
  entryMap: Map<string, any>,
  mode: "class" | "teacher"
): TimetableRow[] {
  return periods.map((period) => {
    const timeLabel = `${formatTime(period.start_time)} – ${formatTime(period.end_time)}`;
    const periodLabel = `${period.name}\n(${timeLabel})`;

    if (period.is_break) {
      return { periodLabel, cells: DAYS.map(() => "— BREAK —"), isBreak: true };
    }

    const cells = DAYS.map((_, dayIndex) => {
      const entry = entryMap.get(`${dayIndex}-${period.id}`);
      if (!entry) return "";
      if (mode === "class") {
        const subject = (entry as any)?.subjects?.name || entry?.subject_name || "";
        const teacher = (entry as any)?.teachers?.name || entry?.teacher_name || "";
        return teacher ? `${subject}\n(${teacher})` : subject;
      } else {
        const subject = (entry as any)?.subjects?.name || entry?.subject_name || "";
        const cls = (entry as any)?.classes?.name || entry?.class_name || "";
        return cls ? `${subject}\n[${cls}]` : subject;
      }
    });

    return { periodLabel, cells, isBreak: false };
  });
}

// ─── PDF export ──────────────────────────────────────────────────────────────

const PERIOD_COLOR: [number, number, number] = [255, 193, 7];   // amber header
const DAY_COLOR: [number, number, number]    = [33, 150, 243];  // blue header
const BREAK_BG: [number, number, number]     = [255, 248, 220]; // cream
const ALT_ROW: [number, number, number]      = [245, 245, 245]; // light grey

export function exportTimetablePDF(
  title: string,
  subtitle: string,
  rows: TimetableRow[]
) {
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });

  // ── School / title header ──
  doc.setFillColor(30, 41, 59);
  doc.rect(0, 0, 297, 22, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text(title, 297 / 2, 10, { align: "center" });

  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.text(subtitle, 297 / 2, 17, { align: "center" });

  // ── Table ──
  const head = [["Period", ...DAYS]];
  const body = rows.map((r) => [r.periodLabel, ...r.cells]);

  autoTable(doc, {
    startY: 26,
    head,
    body,
    styles: {
      fontSize: 7.5,
      cellPadding: 2.5,
      lineColor: [200, 200, 200],
      lineWidth: 0.3,
      overflow: "linebreak",
      valign: "middle",
    },
    headStyles: {
      fillColor: [30, 41, 59],
      textColor: [255, 255, 255],
      fontStyle: "bold",
      halign: "center",
    },
    columnStyles: {
      0: {
        fillColor: PERIOD_COLOR,
        textColor: [30, 41, 59],
        fontStyle: "bold",
        halign: "center",
        cellWidth: 32,
      },
    },
    didParseCell(data) {
      if (data.section === "head" && data.column.index > 0) {
        data.cell.styles.fillColor = DAY_COLOR;
      }
      if (data.section === "body") {
        const row = rows[data.row.index];
        if (row?.isBreak) {
          data.cell.styles.fillColor = BREAK_BG;
          data.cell.styles.textColor = [160, 120, 0];
          data.cell.styles.halign = "center";
          data.cell.styles.fontStyle = "italic";
        } else if (data.row.index % 2 === 0) {
          if (data.column.index > 0) {
            data.cell.styles.fillColor = ALT_ROW;
          }
        }
      }
    },
    margin: { left: 10, right: 10 },
  });

  // ── Footer ──
  const pageH = doc.internal.pageSize.height;
  doc.setFontSize(7);
  doc.setTextColor(150);
  doc.text(
    `Generated by School Blossom  •  ${new Date().toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" })}`,
    297 / 2,
    pageH - 5,
    { align: "center" }
  );

  const safeName = title.replace(/[^a-z0-9]/gi, "_").toLowerCase();
  doc.save(`${safeName}_timetable.pdf`);
}

// ─── Excel export ─────────────────────────────────────────────────────────────

export function exportTimetableExcel(
  title: string,
  subtitle: string,
  rows: TimetableRow[]
) {
  const wb = XLSX.utils.book_new();

  const wsData: (string | null)[][] = [
    [title, null, null, null, null, null, null],
    [subtitle, null, null, null, null, null, null],
    [],
    ["Period / Time", ...DAYS],
    ...rows.map((r) => [r.periodLabel.replace("\n", " "), ...r.cells.map((c) => c.replace("\n", " "))]),
  ];

  const ws = XLSX.utils.aoa_to_sheet(wsData);

  // Column widths
  ws["!cols"] = [
    { wch: 28 },
    ...DAYS.map(() => ({ wch: 22 })),
  ];

  // Row heights
  ws["!rows"] = [
    { hpx: 22 },
    { hpx: 16 },
    { hpx: 6 },
    { hpx: 18 },
    ...rows.map(() => ({ hpx: 36 })),
  ];

  XLSX.utils.book_append_sheet(wb, ws, "Timetable");

  const safeName = title.replace(/[^a-z0-9]/gi, "_").toLowerCase();
  XLSX.writeFile(wb, `${safeName}_timetable.xlsx`);
}

// ─── Word export (.docx as styled HTML saved as .doc) ────────────────────────
// Uses an HTML blob that Word/LibreOffice can open natively.

export function exportTimetableWord(
  title: string,
  subtitle: string,
  rows: TimetableRow[]
) {
  const dayHeaders = DAYS.map(
    (d) => `<th style="background:#1e293b;color:#fff;padding:8px 12px;font-size:11pt;font-weight:bold;text-align:center;border:1px solid #ccc;">${d}</th>`
  ).join("");

  const tableRows = rows
    .map((r) => {
      const tdStyle = r.isBreak
        ? "background:#fff8dc;color:#8a6500;font-style:italic;text-align:center;font-size:9pt;"
        : "background:#fff;font-size:9pt;";

      const periodTd = `<td style="background:#ffc107;color:#1e293b;font-weight:bold;font-size:9pt;vertical-align:middle;text-align:center;padding:6px 8px;border:1px solid #ccc;white-space:pre-line;">${r.periodLabel}</td>`;
      const dataTds = r.cells
        .map(
          (cell) =>
            `<td style="${tdStyle}vertical-align:middle;padding:6px 8px;border:1px solid #ccc;white-space:pre-line;">${cell || ""}</td>`
        )
        .join("");
      return `<tr>${periodTd}${dataTds}</tr>`;
    })
    .join("");

  const html = `
<html xmlns:o="urn:schemas-microsoft-com:office:office"
      xmlns:w="urn:schemas-microsoft-com:office:word"
      xmlns="http://www.w3.org/TR/REC-html40">
<head>
  <meta charset="utf-8"/>
  <title>${title}</title>
  <!--[if gte mso 9]>
  <xml><w:WordDocument><w:View>Print</w:View><w:Zoom>90</w:Zoom><w:DoNotOptimizeForBrowser/></w:WordDocument></xml>
  <![endif]-->
  <style>
    body { font-family: Calibri, Arial, sans-serif; margin: 20mm; }
    table { border-collapse: collapse; width: 100%; page-break-inside: avoid; }
  </style>
</head>
<body>
  <div style="background:#1e293b;padding:16px;margin-bottom:12px;border-radius:4px;">
    <h1 style="color:#fff;font-size:16pt;font-weight:bold;text-align:center;margin:0 0 4px;">${title}</h1>
    <p style="color:#94a3b8;font-size:10pt;text-align:center;margin:0;">${subtitle}</p>
  </div>
  <table>
    <thead>
      <tr>
        <th style="background:#ffc107;color:#1e293b;padding:8px 12px;font-size:11pt;font-weight:bold;text-align:center;border:1px solid #ccc;">Period / Time</th>
        ${dayHeaders}
      </tr>
    </thead>
    <tbody>
      ${tableRows}
    </tbody>
  </table>
  <p style="margin-top:16px;font-size:8pt;color:#888;text-align:center;">
    Generated by School Blossom &bull; ${new Date().toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" })}
  </p>
</body>
</html>`;

  const blob = new Blob(["\ufeff", html], {
    type: "application/msword;charset=utf-8",
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  const safeName = title.replace(/[^a-z0-9]/gi, "_").toLowerCase();
  a.href = url;
  a.download = `${safeName}_timetable.doc`;
  a.click();
  URL.revokeObjectURL(url);
}
